// The agent's changes to its skills (skill_manage). Everything stays under skills/<dir>/, never
// through a symlink and never in a hidden directory; the build's generated skills are refused.
// What the agent writes here is Learning: the nap keeps it, rehydrate brings it back, and the
// dream proposes it for review like a Hermes agent's own skills.

var nameRe = regexp.MustCompile(`^[a-z0-9][a-z0-9_-]{0,63}$`)

// frontMatter is a SKILL.md's front matter: whether it has one, and its name and description.
func frontMatter(body []byte) (name, description string, ok bool) {
	body = bytes.TrimPrefix(body, []byte("\xef\xbb\xbf"))
	if !bytes.HasPrefix(body, []byte("---")) {
		return "", "", false
	}
	rest := body[3:]
	end := bytes.Index(rest, []byte("\n---"))
	if end < 0 {
		return "", "", false
	}
	var fm struct {
		Name        string `yaml:"name"`
		Description string `yaml:"description"`
	}
	if yaml.Unmarshal(rest[:end], &fm) != nil {
		return "", "", false
	}
	return strings.TrimSpace(fm.Name), strings.TrimSpace(fm.Description), true
}

const skillMDHelp = "a SKILL.md starts with front matter:\n---\nname: <name>\ndescription: <when to use it, one line>\n---"

// checkSkillMD refuses a SKILL.md that would not index as the skill it is written for: the name
// the index gives it (its front matter's, else its directory's, leaf) must stay want, and a skill
// with a description keeps one, of at most MaxDescription characters (prev is the SKILL.md it
// replaces, nil for a new skill: a description that was already longer may stay as it was).
// needFront asks for front matter (a new skill); a repo skill without any may stay without.
func checkSkillMD(body, prev []byte, leaf, want string, needDesc, needFront bool) error {
	if len(body) > MaxFile {
		return fmt.Errorf("SKILL.md is over %d bytes", MaxFile)
	}
	name, desc, ok := frontMatter(body)
	if !ok && needFront {
		return errors.New("no front matter: " + skillMDHelp)
	}
	indexed := oneLine(name)
	if indexed == "" {
		indexed = leaf
	}
	_, prevDesc, _ := frontMatter(prev)
	switch {
	case indexed != want:
		return fmt.Errorf("the skill's name would become %q, it is %q: a skill is not renamed (create the new one and delete this one)", indexed, want)
	case needDesc && desc == "":
		return errors.New("front matter needs a description: " + skillMDHelp)
	case utf8.RuneCountInString(oneLine(desc)) > MaxDescription && (prev == nil || desc != prevDesc):
		return fmt.Errorf("the description is over %d characters: say in one line when to use the skill, and put the rest in the body", MaxDescription)
	}
	return nil
}

// current is s's SKILL.md as it is now.
func (l *Library) current(s Skill) ([]byte, error) {
	p, err := l.real(s.Path)
	if err != nil {
		return nil, err
	}
	body, _, err := readRegular(p, MaxFile)
	return body, err
}

// writable is s, refused when the agent may not change it.
func (l *Library) writable(s Skill) error {
	if l.ReadOnly(s.Dir) {
		return fmt.Errorf("%s is generated by the build (or hidden) and cannot be changed; keep notes in your own skill or in memory", s.Dir)
	}
	return nil
}

// write writes rel (relative to the home) atomically, its parent directories made 0755 as
// rehydrate makes them.
func (l *Library) write(rel string, body []byte) error {
	p, err := l.real(rel)
	if err != nil {
		return err
	}
	if info, err := os.Lstat(p); err == nil && !info.Mode().IsRegular() {
		return fmt.Errorf("%s is not a regular file", rel)
	}
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	// the parents may have been made just now: none of them is a link
	if _, err := l.real(rel); err != nil {
		return err
	}
	return fsx.WriteAtomicIn(p, l.tmp(), body, 0o644)
}

// Create makes skills/[<category>/]<name>/SKILL.md with content, recorded as the agent's own.
func (l *Library) Create(name, category, content string) (Skill, error) {
	l.mu.Lock()
	defer l.mu.Unlock()
	if !nameRe.MatchString(name) {
		return Skill{}, fmt.Errorf("name %q: use lowercase letters, digits, - and _ (at most 64)", name)
	}
	dir := name
	if category != "" {
		if !nameRe.MatchString(category) {
			return Skill{}, fmt.Errorf("category %q: use lowercase letters, digits, - and _ (one directory)", category)
		}
		dir = category + "/" + name
	}
	if l.ReadOnly(dir) {
		return Skill{}, fmt.Errorf("%s is the name of a skill the build generates", name)
	}
	for _, s := range l.Index() {
		switch {
		case s.Name == name || path.Base(s.Dir) == name:
			return Skill{}, fmt.Errorf("a skill named %s exists (%s): change it with edit or patch", name, s.Dir)
		case strings.HasPrefix(dir, s.Dir+"/"):
			return Skill{}, fmt.Errorf("%s would be inside skill %s", dir, s.Dir)
		case strings.HasPrefix(s.Dir, dir+"/"):
			return Skill{}, fmt.Errorf("%s would contain skill %s", dir, s.Dir)
		}
	}
	p, err := l.real("skills/" + dir)
	if err != nil {
		return Skill{}, err
	}
	if _, err := os.Lstat(p); err == nil {
		return Skill{}, fmt.Errorf("skills/%s exists already", dir)
	}
	content = l.Unresolve(Skill{Dir: dir}, content)
	if err := checkSkillMD([]byte(content), nil, name, name, true, true); err != nil {
		return Skill{}, err
	}
	if err := l.check("SKILL.md", []byte(content)); err != nil {
		return Skill{}, err
	}
	if err := l.write("skills/"+dir+"/SKILL.md", []byte(content)); err != nil {
		return Skill{}, err
	}
	_, desc, _ := frontMatter([]byte(content))
	s := Skill{Name: name, Description: strings.Join(strings.Fields(desc), " "), Path: "skills/" + dir + "/SKILL.md", Dir: dir}
	l.created(s)
	return s, nil
}

// Edit replaces the SKILL.md of the skill name names.
func (l *Library) Edit(name, content string) (Skill, error) {
	l.mu.Lock()
	defer l.mu.Unlock()
	s, err := l.Find(name)
	if err != nil {
		return Skill{}, err
	}
	if err := l.writable(s); err != nil {
		return Skill{}, err
	}
	prev, err := l.current(s)
	if err != nil {
		return Skill{}, err
	}
	content = l.Unresolve(s, content)
	if err := checkSkillMD([]byte(content), prev, path.Base(s.Dir), s.Name, s.Description != "", false); err != nil {
		return Skill{}, err
	}
	if err := l.check("SKILL.md", []byte(content)); err != nil {
		return Skill{}, err
	}
	if err := l.write(s.Path, []byte(content)); err != nil {
		return Skill{}, err
	}
	l.patched(s)
	return s, nil
}

// fileOf is a file of s to change: SKILL.md when file is empty.
func (l *Library) fileOf(s Skill, file string) (string, error) {
	if strings.TrimSpace(file) == "" || path.Clean(filepath.ToSlash(strings.TrimSpace(file))) == "SKILL.md" {
		return "SKILL.md", nil
	}
	rel, err := cleanRel(file)
	if err != nil {
		return "", err
	}
	if err := notSkillMD(rel); err != nil {
		return "", err
	}
	if strings.HasSuffix(rel, ".luau") && l.CheckLuau == nil {
		return "", errors.New("Luau tools (.luau) are not enabled in this runtime")
	}
	return rel, nil
}

// notSkillMD refuses a file other than the skill's own SKILL.md named SKILL.md in any case: below
// the skill it would make a skill of its own, bypassing create's checks (and on a case-insensitive
// filesystem skill.md is the skill's own).
func notSkillMD(rel string) error {
	if strings.EqualFold(path.Base(rel), "SKILL.md") {
		return fmt.Errorf("%s: a file named SKILL.md would be a skill of its own; make a new skill with create, and change this one's SKILL.md with edit or patch", rel)
	}
	return nil
}

// check refuses body for rel when l.Check does, and a .luau file CheckLuau refuses (an invalid
// header, a file outside tools/, source that does not compile).
func (l *Library) check(rel string, body []byte) error {
	if l.Check != nil {
		if err := l.Check(string(body)); err != nil {
			return fmt.Errorf("%s: %w", rel, err)
		}
	}
	if strings.HasSuffix(rel, ".luau") && l.CheckLuau != nil {
		return l.CheckLuau(rel, body)
	}
	return nil
}

// inNested refuses a file of s that lies in a skill nested inside it.
func (l *Library) inNested(s Skill, rel string) error {
	full := s.Dir + "/" + rel
	for _, o := range l.Index() {
		if strings.HasPrefix(o.Dir, s.Dir+"/") && strings.HasPrefix(full, o.Dir+"/") {
			return fmt.Errorf("%s belongs to skill %s", rel, o.Dir)
		}
	}
	return nil
}

// Patch replaces old with repl in one file of the skill name names (SKILL.md when file is empty):
// old must appear exactly once, or all is set. It returns how many were replaced.
func (l *Library) Patch(name, file, old, repl string, all bool) (Skill, string, int, error) {
	l.mu.Lock()
	defer l.mu.Unlock()
	s, err := l.Find(name)
	if err != nil {
		return Skill{}, "", 0, err
	}
	if err := l.writable(s); err != nil {
		return Skill{}, "", 0, err
	}
	rel, err := l.fileOf(s, file)
	if err != nil {
		return Skill{}, "", 0, err
	}
	if err := l.inNested(s, rel); err != nil {
		return Skill{}, "", 0, err
	}
	if old == "" {
		return Skill{}, "", 0, errors.New("old_string is empty")
	}
	p, err := l.real("skills/" + s.Dir + "/" + rel)
	if err != nil {
		return Skill{}, "", 0, err
	}
	body, cut, err := readRegular(p, MaxFile)
	if errors.Is(err, fs.ErrNotExist) {
		return Skill{}, "", 0, fmt.Errorf("%s has no file %s", s.Dir, rel)
	}
	if err != nil {
		return Skill{}, "", 0, err
	}
	if cut {
		return Skill{}, "", 0, fmt.Errorf("%s is over %d bytes", rel, MaxFile)
	}
	// old_string and new_string come from a view, where ${SKILL_DIR} is resolved; a file that
	// holds the literal directory (written by the terminal) is still matched by it.
	if u := l.Unresolve(s, old); u != old && strings.Contains(string(body), u) {
		old = u
	}
	repl = l.Unresolve(s, repl)
	n := strings.Count(string(body), old)
	switch {
	case n == 0:
		return Skill{}, "", 0, fmt.Errorf("old_string was not found in %s/%s", s.Dir, rel)
	case n > 1 && !all:
		return Skill{}, "", 0, fmt.Errorf("old_string appears %d times in %s/%s: give more of the text around it, or set replace_all", n, s.Dir, rel)
	}
	out := []byte(strings.ReplaceAll(string(body), old, repl))
	if len(out) > MaxFile {
		return Skill{}, "", 0, fmt.Errorf("%s would be over %d bytes", rel, MaxFile)
	}
	if rel == "SKILL.md" {
		if err := checkSkillMD(out, body, path.Base(s.Dir), s.Name, s.Description != "", false); err != nil {
			return Skill{}, "", 0, err
		}
	}
	if err := l.check(rel, out); err != nil {
		return Skill{}, "", 0, err
	}
	if err := l.write("skills/"+s.Dir+"/"+rel, out); err != nil {
		return Skill{}, "", 0, err
	}
	l.patched(s)
	return s, rel, n, nil
}

// WriteFile writes one file (not SKILL.md) of the skill name names: a reference, a template, a
// script.
func (l *Library) WriteFile(name, file, content string) (Skill, string, error) {
	l.mu.Lock()
	defer l.mu.Unlock()
	s, err := l.Find(name)
	if err != nil {
		return Skill{}, "", err
	}
	if err := l.writable(s); err != nil {
		return Skill{}, "", err
	}
	rel, err := l.fileOf(s, file)
	if err != nil {
		return Skill{}, "", err
	}
	if rel == "SKILL.md" {
		return Skill{}, "", errors.New("change SKILL.md with edit or patch")
	}
	if err := l.inNested(s, rel); err != nil {
		return Skill{}, "", err
	}
	content = l.Unresolve(s, content)
	if len(content) > MaxFile {
		return Skill{}, "", fmt.Errorf("%s would be over %d bytes", rel, MaxFile)
	}
	if err := l.check(rel, []byte(content)); err != nil {
		return Skill{}, "", err
	}
	if err := l.write("skills/"+s.Dir+"/"+rel, []byte(content)); err != nil {
		return Skill{}, "", err
	}
	l.patched(s)
	return s, rel, nil
}

// RemoveFile removes one file (not SKILL.md) of the skill name names, and the directories it
// leaves empty inside the skill.
func (l *Library) RemoveFile(name, file string) (Skill, string, error) {
	l.mu.Lock()
	defer l.mu.Unlock()
	s, err := l.Find(name)
	if err != nil {
		return Skill{}, "", err
	}
	if err := l.writable(s); err != nil {
		return Skill{}, "", err
	}
	rel, err := cleanRel(file)
	if err != nil {
		return Skill{}, "", err
	}
	if rel == "SKILL.md" {
		return Skill{}, "", errors.New("SKILL.md is the skill: delete the skill instead")
	}
	if err := notSkillMD(rel); err != nil {
		return Skill{}, "", err
	}
	if err := l.inNested(s, rel); err != nil {
		return Skill{}, "", err
	}
	p, err := l.real("skills/" + s.Dir + "/" + rel)
	if err != nil {
		return Skill{}, "", err
	}
	info, err := os.Lstat(p)
	if err != nil {
		return Skill{}, "", fmt.Errorf("%s has no file %s", s.Dir, rel)
	}
	if !info.Mode().IsRegular() {
		return Skill{}, "", fmt.Errorf("%s is not a regular file", rel)
	}
	if err := os.Remove(p); err != nil {
		return Skill{}, "", err
	}
	top := l.Abs(s)
	for d := filepath.Dir(p); d != top && strings.HasPrefix(d, top+string(filepath.Separator)); d = filepath.Dir(d) {
		if os.Remove(d) != nil { // not empty
			break
		}
	}
	l.patched(s)
	return s, rel, nil
}

// Delete removes the skill name names, with everything in its directory.
func (l *Library) Delete(name string) (Skill, error) {
	l.mu.Lock()
	defer l.mu.Unlock()
	s, err := l.Find(name)
	if err != nil {
		return Skill{}, err
	}
	if err := l.writable(s); err != nil {
		return Skill{}, err
	}
	for _, o := range l.Index() {
		if strings.HasPrefix(o.Dir, s.Dir+"/") {
			return Skill{}, fmt.Errorf("%s holds skill %s: delete that one first", s.Dir, o.Dir)
		}
	}
	if l.booted(s.Dir) {
		return Skill{}, fmt.Errorf("%s comes from the agent's repository: deleted here, it would come back at the next restart (rehydrate restores it) and no deletion is proposed for review. Change it with edit or patch, or ask a person to remove it from the repository", s.Dir)
	}
	p, err := l.real("skills/" + s.Dir)
	if err != nil {
		return Skill{}, err
	}
	// One rename takes the skill out of skills/ (a nap taken meanwhile sees all of it or none);
	// its files are removed from the unclaimed temp dir, which boot sweeps if this is cut short.
	if err := os.MkdirAll(l.tmp(), 0o700); err != nil {
		return Skill{}, err
	}
	gone, err := os.MkdirTemp(l.tmp(), "deleted-")
	if err != nil {
		return Skill{}, err
	}
	if err := os.Rename(p, filepath.Join(gone, "skill")); err != nil {
		_ = os.Remove(gone)
		return Skill{}, err
	}
	_ = fsx.RemoveAll(gone)
	l.deleted(s)
	return s, nil
}

// BootedFile is where rehydrate records, in the home, the baseline the instance booted from
// (pkg/loop.BootedPath): {"gitSha", "skills": {dir: hash}, "settings"}. Its skills are the
// agent's repository's.
const BootedFile = ".swarm/booted.json"

// booted reports a skill dir the instance booted with from the agent's repository. Without a
// readable booted.json (a bench, a test home) none is.
func (l *Library) booted(dir string) bool {
	body, err := os.ReadFile(filepath.Join(l.Home, filepath.FromSlash(BootedFile)))
	if err != nil {
		return false
	}
	var b struct {
		Skills map[string]string `json:"skills"`
	}
	if json.Unmarshal(body, &b) != nil {
		return false
	}
	_, ok := b.Skills[dir]
	return ok
}
